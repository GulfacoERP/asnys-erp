export function quotePdf(o: { company: Company; quote: any; customer: any; lines: any[] }) {
  const { company: c, quote: q, customer: cu, lines } = o;
  const cur = ccy(q);
  const isOrder = q.kind === 'order';
  const doc = newDoc();
  let y = header(doc, c, isOrder ? 'Sales order' : 'Quotation', [
    [isOrder ? 'Order no.' : 'Quote no.', q.number || '—'], ['Date', longDate(q.quote_date)], ...(isOrder ? [] : [['Valid until', longDate(q.valid_until) || '—']] as [string, string][]),
  ]);
  y = block(doc, isOrder ? 'Customer' : 'Prepared for', [cu?.name, cu?.address, cu?.city, cu?.phone], M, y) + 14;
  y = lineTable(doc, y, lines, cur, 'unit_price', 'Unit price', l => (l.taxable ? '' : '  (exempt)'));
  const sub = lines.reduce((a, l) => a + Number(l.qty) * Number(l.unit_price), 0);
  const tx = lines.filter(l => l.taxable).reduce((a, l) => a + Number(l.qty) * Number(l.unit_price), 0);
  const vat = Math.round(tx * 15) / 100, nhil = Math.round(tx * 2.5) / 100, getf = Math.round(tx * 2.5) / 100;
  y = totals(doc, [['Subtotal', money(sub)], ['VAT 15%', money(vat)], ['NHIL 2.5%', money(nhil)], ['GETFund levy 2.5%', money(getf)],
    [`Total (${cur})`, money(sub + vat + nhil + getf), true]], y);
  if (fxNote(q)) y = note(doc, fxNote(q), y);
  if (q.notes) y = note(doc, q.notes, y);
  if (!isOrder) note(doc, 'Prices include VAT, NHIL and GETFund levy at the rates in force on the quote date. Final tax is calculated on the invoice.', y);
  footer(doc);
  doc.save(safeName(`${q.number || 'quote'}-${cu?.name || ''}`) + '.pdf');
}

