export function appraisalPdf(c: Company, a: any, e: any) {
  const doc = newDoc();
  let y = header(doc, c, 'Performance appraisal', [['Period', a.period_label], ['Review date', longDate(a.review_date)], ['Rating', a.rating ? `${a.rating} of 5` : '—']]);
  y = block(doc, 'Employee', [e?.full_name, [e?.job_title, e?.department].filter(Boolean).join(', '), a.reviewer ? 'Reviewer: ' + a.reviewer : null], M, y) + 18;
  const W = doc.internal.pageSize.getWidth();
  for (const [label, text] of [['Achievements', a.achievements], ['Strengths', a.strengths], ['Areas to improve', a.improvements], ['Goals for next period', a.goals], ['Employee comments', a.employee_comments]] as [string, string][]) {
    if (!text) continue;
    if (y > doc.internal.pageSize.getHeight() - 120) { doc.addPage(); y = 50; }
    doc.setFont('helvetica', 'bold'); doc.setFontSize(10); doc.setTextColor(...GREEN); doc.text(label, M, y);
    doc.setFont('helvetica', 'normal'); doc.setFontSize(9.5); doc.setTextColor(...INK);
    const lines = doc.splitTextToSize(text, W - 2 * M);
    doc.text(lines, M, y + 14);
    y += 14 + lines.length * 12 + 14;
  }
  y = Math.max(y + 20, doc.internal.pageSize.getHeight() - 110);
  doc.setDrawColor(...MUTED); doc.setLineWidth(0.5);
  doc.line(M, y, M + 200, y); doc.line(W - M - 200, y, W - M, y);
  doc.setFontSize(8.5); doc.setTextColor(...MUTED);
  doc.text('Employee signature and date', M, y + 12); doc.text('Reviewer signature and date', W - M - 200, y + 12);
  footer(doc);
  doc.save(safeName(`appraisal-${a.period_label}-${e?.full_name || ''}`) + '.pdf');
}

