export function statementPdf(o: { company: Company; party: any; kind: 'customer' | 'supplier'; docs: any[]; payments: any[]; credits?: any[] }) {
  const { company: c, party, kind, docs, payments } = o;
  const doc = newDoc();
  let y = header(doc, c, 'Statement of account', [['Date', longDate(new Date().toISOString())], ['Account', party.name]]);
  y = block(doc, kind === 'customer' ? 'Customer' : 'Supplier', [party.name, party.address, party.city, party.phone], M, y) + 14;
  type Row = { date: string; ref: string; desc: string; charge: number; paid: number };
  const rate = (d: any) => Number(d?.exchange_rate || 1);
  const rows: Row[] = [
    ...docs.filter(d => d.status !== 'draft').map(d => ({ date: d.invoice_date || d.bill_date, ref: d.number, desc: (kind === 'customer' ? 'Invoice' : 'Bill') + (d.currency && d.currency !== 'GHS' ? ` (${d.currency} ${money(d.total)})` : ''), charge: Number(d.total) * rate(d), paid: 0 })),
    ...(o.credits || []).filter(cn => cn.status === 'posted').map(cn => ({ date: cn.credit_date, ref: cn.number, desc: 'Credit note', charge: 0, paid: Number(cn.total) * rate(cn) })),
    ...payments.map(p => ({ date: p.payment_date, ref: p.reference || '', desc: 'Payment, ' + methodName(p.method), charge: 0, paid: Number(p.amount) * rate(p.doc) })),
  ].sort((a, b) => a.date.localeCompare(b.date));
  let bal = 0;
  table(doc, { ...tableStyle, startY: y, head: [['Date', 'Reference', 'Details', 'Charges', 'Payments / credits', 'Balance (GHS)']],
    body: rows.map(r => { bal += r.charge - r.paid; return [longDate(r.date), r.ref, r.desc, r.charge ? money(r.charge) : '', r.paid ? money(r.paid) : '', money(bal)]; }),
    foot: [['', '', bal < 0 ? 'Credit balance' : 'Balance due', '', '', money(bal)]],
    columnStyles: { 3: { halign: 'right' }, 4: { halign: 'right' }, 5: { halign: 'right' } } });
  footer(doc);
  doc.save(safeName(`statement-${party.name}`) + '.pdf');
}

