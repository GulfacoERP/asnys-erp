// The built-in PDF fonts have no cedi sign, so documents use the ISO code "GHS".
const GREEN: [number, number, number] = [29, 107, 85];
const INK: [number, number, number] = [23, 35, 30];
const MUTED: [number, number, number] = [91, 107, 99];
const M = 40; // page margin in points
/** The built-in PDF fonts have no cedi sign: print the ISO code instead. */
const cedi = (t: any) => String(t ?? '').replace(/GH₵/g, 'GHS').replace(/₵/g, 'GHS');

type Company = { name: string; tin?: string | null; address?: string | null; city?: string | null; phone?: string | null; email?: string | null; bank_details?: string | null; momo_details?: string | null };

function newDoc(landscape = false) {
  return new jsPDF({ unit: 'pt', format: 'a4', orientation: landscape ? 'landscape' : 'portrait' });
}

/** Company block on the left, document title and meta on the right. Returns the y below it.
 *  Each side keeps to its own half of the page; long titles wrap (and shrink) instead of running into the company name. */
function header(doc: jsPDF, c: Company, title: string, meta: [string, string][] = [], subtitle?: string) {
  title = cedi(title); subtitle = subtitle && cedi(subtitle); meta = meta.map(([k, v]) => [cedi(k), cedi(v)]);
  const W = doc.internal.pageSize.getWidth();
  const half = (W - 2 * M) / 2 - 12;
  doc.setFillColor(...GREEN);
  doc.rect(0, 0, W, 6, 'F');
  // Left: company
  doc.setTextColor(...INK);
  doc.setFont('helvetica', 'bold'); doc.setFontSize(15);
  const name: string[] = doc.splitTextToSize(c.name, half);
  name.forEach((l, i) => doc.text(l, M, 46 + i * 17));
  let ly = 46 + (name.length - 1) * 17 + 16;
  doc.setFont('helvetica', 'normal'); doc.setFontSize(9); doc.setTextColor(...MUTED);
  const lines = [c.address, c.city, [c.phone, c.email].filter(Boolean).join('  ·  '), c.tin ? 'TIN ' + c.tin : null].filter(Boolean) as string[];
  lines.forEach(l => { (doc.splitTextToSize(l, half) as string[]).forEach(x => { doc.text(x, M, ly); ly += 12; }); });
  // Right: title, wrapped to the right half, at most three lines
  let size = 18;
  doc.setFont('helvetica', 'bold');
  let tl: string[] = [];
  for (; size >= 11; size -= 1) { doc.setFontSize(size); tl = doc.splitTextToSize(title.toUpperCase(), half); if (tl.length <= (size > 14 ? 1 : 3)) break; }
  tl = tl.slice(0, 3);
  doc.setTextColor(...GREEN);
  const lh = size * 1.15;
  tl.forEach((l, i) => doc.text(l, W - M, 46 + i * lh, { align: 'right' }));
  let ry = 46 + (tl.length - 1) * lh + 16;
  if (subtitle) {
    doc.setFont('helvetica', 'normal'); doc.setFontSize(9); doc.setTextColor(...MUTED);
    (doc.splitTextToSize(subtitle, half) as string[]).slice(0, 3).forEach(l => { doc.text(l, W - M, ry, { align: 'right' }); ry += 12; });
    ry += 2;
  }
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  const valueW = Math.min(half - 70, Math.max(60, ...meta.map(([, v]) => doc.getTextWidth(v))));
  meta.forEach(([k, v]) => {
    doc.setFont('helvetica', 'normal'); doc.setTextColor(...MUTED);
    doc.text(k, W - M - valueW - 12, ry, { align: 'right' });
    doc.setFont('helvetica', 'bold'); doc.setTextColor(...INK);
    const vl: string[] = doc.splitTextToSize(v, valueW);
    vl.forEach((x, j) => doc.text(x, W - M, ry + j * 11, { align: 'right' }));
    ry += 13 + (vl.length - 1) * 11;
  });
  return Math.max(ly, ry) + 18;
}

function footer(doc: jsPDF) {
  const n = doc.getNumberOfPages();
  const W = doc.internal.pageSize.getWidth(), H = doc.internal.pageSize.getHeight();
  for (let i = 1; i <= n; i++) {
    doc.setPage(i);
    doc.setFont('helvetica', 'normal'); doc.setFontSize(8); doc.setTextColor(...MUTED);
    doc.text(`Generated by ${BRAND}`, M, H - 22);
    doc.text(`Page ${i} of ${n}`, W - M, H - 22, { align: 'right' });
  }
}

function block(doc: jsPDF, label: string, lines: (string | null | undefined)[], x: number, y: number) {
  doc.setFont('helvetica', 'bold'); doc.setFontSize(8); doc.setTextColor(...MUTED);
  doc.text(label.toUpperCase(), x, y);
  doc.setFontSize(10); doc.setTextColor(...INK);
  const clean = lines.filter(Boolean) as string[];
  clean.forEach((l, i) => { doc.setFont('helvetica', i === 0 ? 'bold' : 'normal'); doc.text(l, x, y + 14 + i * 12); });
  return y + 14 + clean.length * 12;
}

const tableStyle = {
  theme: 'plain' as const,
  styles: { font: 'helvetica', fontSize: 9, textColor: INK, cellPadding: { top: 5, bottom: 5, left: 6, right: 6 } },
  headStyles: { fillColor: [238, 242, 239] as [number, number, number], textColor: MUTED, fontStyle: 'bold' as const },
  footStyles: { fillColor: [255, 255, 255] as [number, number, number], textColor: INK, fontStyle: 'bold' as const },
  margin: { left: M, right: M },
};

/** autoTable with header and footer cells aligned like their body column. */
function table(doc: jsPDF, opts: any) {
  const right = new Set(Object.entries(opts.columnStyles || {}).filter(([, v]: any) => v.halign === 'right').map(([k]) => Number(k)));
  const user = opts.didParseCell;
  autoTable(doc, { ...opts, didParseCell: (d: any) => {
    if (right.has(d.column.index)) d.cell.styles.halign = 'right';
    if (user) user(d);
  } });
}

const endY = (doc: jsPDF) => (doc as any).lastAutoTable.finalY as number;

/** Right-aligned label/value rows (totals). */
function totals(doc: jsPDF, rows: [string, string, boolean?][], y: number) {
  const W = doc.internal.pageSize.getWidth();
  rows.forEach(([k, v, strong]) => {
    if (strong) { y += 6; doc.setDrawColor(...INK); doc.setLineWidth(0.8); doc.line(W - M - 220, y - 11, W - M, y - 11); }
    doc.setFont('helvetica', strong ? 'bold' : 'normal'); doc.setFontSize(strong ? 11 : 9.5);
    doc.setTextColor(...(strong ? INK : MUTED)); doc.text(k, W - M - 110, y, { align: 'right' });
    doc.setTextColor(...INK); doc.text(v, W - M, y, { align: 'right' });
    y += strong ? 21 : 15;
  });
  return y + 6;
}

function note(doc: jsPDF, text: string, y: number) {
  const W = doc.internal.pageSize.getWidth();
  doc.setFont('helvetica', 'normal'); doc.setFontSize(8.5); doc.setTextColor(...MUTED);
  const wrapped = doc.splitTextToSize(text, W - 2 * M);
  doc.text(wrapped, M, y);
  return y + wrapped.length * 11 + 6;
}

// ---------------------------------------------------------------- Sales and purchase documents

const ccy = (d: any) => (d.currency && d.currency !== 'GHS' ? d.currency : 'GHS');
const fxNote = (d: any) => (d.currency && d.currency !== 'GHS' ? `Amounts in ${d.currency}. Exchange rate used: 1 ${d.currency} = GHS ${Number(d.exchange_rate).toLocaleString('en-GH', { maximumFractionDigits: 6 })}.` : '');

function lineTable(doc: jsPDF, y: number, lines: any[], c: string, priceKey: 'unit_price' | 'unit_cost', priceLabel: string, flag?: (l: any) => string) {
  table(doc, {
    ...tableStyle, startY: y,
    head: [['Description', 'Qty', `${priceLabel} (${c})`, `Amount (${c})`]],
    body: lines.map(l => [l.description + (flag ? flag(l) : ''), qty(l.qty), money(l[priceKey]), money(Number(l.qty) * Number(l[priceKey]))]),
    columnStyles: { 1: { halign: 'right' }, 2: { halign: 'right' }, 3: { halign: 'right' } },
  });
  return endY(doc) + 20;
}

function payTable(doc: jsPDF, y: number, payments: any[], c: string) {
  if (!payments.length) return y;
  table(doc, { ...tableStyle, startY: y, head: [['Payment date', 'Method', 'Reference', `Amount (${c})`]],
    body: payments.map(p => [longDate(p.payment_date), methodName(p.method), p.reference || '', money(p.amount)]),
    columnStyles: { 3: { halign: 'right' } } });
  return endY(doc) + 16;
}

export function invoicePdf(o: { company: Company; invoice: any; customer: any; lines: any[]; payments: any[]; credits?: any[] }) {
  const { company: c, invoice: inv, customer: cu, lines, payments } = o;
  const cur = ccy(inv);
  const doc = newDoc();
  let y = header(doc, c, inv.status !== 'draft' ? 'Tax invoice' : 'Draft invoice', [
    ['Invoice no.', inv.number || 'Draft'], ['Date', longDate(inv.invoice_date)], ['Due', longDate(inv.due_date) || '—'],
  ]);
  y = block(doc, 'Bill to', [cu?.name, cu?.address, cu?.city, cu?.phone, cu?.tin ? 'TIN ' + cu.tin : null], M, y) + 14;
  y = lineTable(doc, y, lines, cur, 'unit_price', 'Unit price', l => (l.taxable ? '' : '  (exempt)'));
  const paid = Number(inv.amount_paid || 0), credited = Number(inv.amount_credited || 0);
  y = totals(doc, [
    ['Taxable value', money(inv.subtotal)], ['VAT 15%', money(inv.vat)], ['NHIL 2.5%', money(inv.nhil)], ['GETFund levy 2.5%', money(inv.getfund)],
    [`Total (${cur})`, money(inv.total), true],
    ...(credited ? [['Credited', money(credited)]] as [string, string][] : []),
    ...(paid ? [['Paid', money(paid)]] as [string, string][] : []),
    ...(paid || credited ? [['Balance due', money(Number(inv.total) - paid - credited), true]] as [string, string, boolean][] : []),
  ], y);
  y = payTable(doc, y, payments, cur);
  const pay = [c.bank_details && 'Bank: ' + c.bank_details, c.momo_details && 'Mobile Money: ' + c.momo_details].filter(Boolean).join('    ');
  if (pay) y = note(doc, 'How to pay — ' + pay + (inv.number ? `. Quote ${inv.number}.` : ''), y);
  if (fxNote(inv)) y = note(doc, fxNote(inv), y);
  if (inv.notes) y = note(doc, inv.notes, y);
  note(doc, 'VAT, NHIL and GETFund levy are charged on the same taxable value under the VAT Act, 2025 (Act 1151).', y);
  footer(doc);
  doc.save(safeName(`${inv.number || 'draft-invoice'}-${cu?.name || ''}`) + '.pdf');
}

