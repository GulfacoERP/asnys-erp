/** Purchase order to send to the supplier. Prices exclude VAT. */
export function purchaseOrderPdf(o: { company: Company; po: any; supplier: any; lines: any[]; deliverTo: string; site?: string | null }) {
  const { company: c, po, supplier: s, lines } = o;
  const doc = newDoc();
  let y = header(doc, c, po.status === 'draft' ? 'Draft purchase order' : 'Purchase order', [
    ['Order no.', po.number || 'Draft'], ['Date', longDate(po.order_date)], ['Deliver by', longDate(po.expected_date) || '—'],
    ...(po.currency && po.currency !== 'GHS' ? [['Currency', po.currency] as [string, string]] : []),
  ]);
  const y1 = block(doc, 'Supplier', [s?.name, s?.contact_name ? 'Attn: ' + s.contact_name : null, s?.address, s?.city, s?.phone, s?.tin ? 'TIN ' + s.tin : null], M, y);
  const y2 = block(doc, 'Deliver to', o.po.project_id ? [o.deliverTo, o.site, 'Call ' + (c.phone || '') + ' before delivery'] : [o.deliverTo, c.address, c.city, c.phone], 300, y);
  y = Math.max(y1, y2) + 14;
  const cur = po.currency && po.currency !== 'GHS' ? po.currency : 'GHS';
  const pl = lines.map(l => ({ ...l, unit_cost: cur === 'GHS' ? l.unit_cost : l.unit_price_fx }));
  y = lineTable(doc, y, pl, cur, 'unit_cost', 'Unit price', l => (l.taxable ? '' : '  (no VAT)'));
  const sub = pl.reduce((a, l) => a + Number(l.qty) * Number(l.unit_cost), 0);
  const taxable = pl.filter(l => l.taxable).reduce((a, l) => a + Number(l.qty) * Number(l.unit_cost), 0);
  const levies = Math.round(taxable * 0.2 * 100) / 100;
  y = totals(doc, cur === 'GHS' || levies > 0 ? [['Subtotal', money(sub)], ['VAT, NHIL and GETFund (est.)', money(levies)], [`Order total (${cur})`, money(sub + levies), true]]
                                            : [[`Order total (${cur})`, money(sub), true]], y);
  y = note(doc, [po.terms, po.notes, 'Please quote our order number on your delivery note and invoice. Goods are accepted only against this order.'].filter(Boolean).join('\n\n'), y);
  doc.setFont('helvetica', 'normal'); doc.setFontSize(9); doc.setTextColor(...MUTED);
  doc.text('Authorised by: ______________________', M, y + 30);
  footer(doc);
  doc.save(safeName(`${po.number || 'draft-po'}-${s?.name || ''}`) + '.pdf');
}

