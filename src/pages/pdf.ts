export type Cell = string | number;
export function tablePdf(o: {
  company: Company; title: string; subtitle?: string; head: string[]; body: Cell[][]; foot?: Cell[];
  rightAlign?: number[]; landscape?: boolean; filename: string; boldRows?: number[]; notes?: string;
}) {
  const doc = newDoc(o.landscape);
  let y = header(doc, o.company, o.title, [], o.subtitle);
  const cols: Record<number, any> = {};
  (o.rightAlign || []).forEach(i => { cols[i] = { halign: 'right' }; });
  table(doc, { ...tableStyle, startY: y, head: [o.head.map(cedi)], body: o.body.map(r => r.map(cedi)), foot: o.foot ? [o.foot.map(cedi)] : undefined,
    columnStyles: cols, showFoot: 'lastPage',
    didParseCell: (d) => { if (d.section === 'body' && o.boldRows?.includes(d.row.index)) d.cell.styles.fontStyle = 'bold'; } });
  if (o.notes) note(doc, cedi(o.notes), endY(doc) + 18);
  footer(doc);
  doc.save(safeName(o.filename) + '.pdf');
}

